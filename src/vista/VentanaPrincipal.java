private void cargarLogo() {
        int tam = 85; // tamaño del logo
        try {
            java.awt.image.BufferedImage hd = javax.imageio.ImageIO.read(getClass().getResource("/vista/logo_hd.png"));
            double[] escalas = {1, 1.25, 1.5, 1.75, 2, 2.5, 3};
            java.awt.Image[] versiones = new java.awt.Image[escalas.length];
            for (int i = 0; i < escalas.length; i++) {
                int t = (int) Math.round(tam * escalas[i]);
                java.awt.image.BufferedImage img = new java.awt.image.BufferedImage(t, t, java.awt.image.BufferedImage.TYPE_INT_ARGB);
                java.awt.Graphics2D g = img.createGraphics();
                g.setRenderingHint(java.awt.RenderingHints.KEY_INTERPOLATION, java.awt.RenderingHints.VALUE_INTERPOLATION_BICUBIC);
                g.setRenderingHint(java.awt.RenderingHints.KEY_RENDERING, java.awt.RenderingHints.VALUE_RENDER_QUALITY);
                g.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
                g.drawImage(hd, 0, 0, t, t, null);
                g.dispose();
                versiones[i] = img;
            }
            jLabel1.setIcon(new javax.swing.ImageIcon(new java.awt.image.BaseMultiResolutionImage(versiones)));
        } catch (Exception e) {
            System.out.println("No se pudo cargar el logo: " + e.getMessage());
        }
        // Nombre del hospital debajo del logo
        jLabel1.setText("Hospital registro de Citas");
        jLabel1.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 18));
        jLabel1.setForeground(new java.awt.Color(21, 101, 192));
        jLabel1.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        jLabel1.setHorizontalTextPosition(javax.swing.SwingConstants.CENTER);
        jLabel1.setVerticalTextPosition(javax.swing.SwingConstants.BOTTOM);
    }
