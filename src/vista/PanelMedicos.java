    // Llena la lista desplegable con las especialidades de la base de datos
    private void llenarCombo() {
    listaEspecialidades = especialidadDAO.listar();
    cbEspecialidad.removeAllItems();
    cbEspecialidad.addItem("Seleccione una especialidad");
    for (modelo.Especialidad e : listaEspecialidades) {
        cbEspecialidad.addItem(e.getNombre());
      }
    }

    // Dibuja la tabla con los médicos de la base de datos
    private void llenarTabla() {
        listaMedicos = medicoDAO.listar();
        modeloTabla.setRowCount(0);
        for (modelo.Medico m : listaMedicos) {
            modeloTabla.addRow(new Object[]{
                m.getCedula(), m.getNombre(), m.getTelefono(), m.getEspecialidadNombre()
            });
        }
    }

    // Vacía los campos del formulario
