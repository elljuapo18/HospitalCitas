    private void btEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEliminarActionPerformed
        int fila = Tbusuarios.getSelectedRow();
if (fila < 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un usuario de la tabla");
    return;
}
modelo.Usuario u = listaUsuarios.get(fila);
if ("admin".equals(u.getUsuario())) {
    javax.swing.JOptionPane.showMessageDialog(this, "No se puede eliminar el administrador principal");
    return;
}
int respuesta = javax.swing.JOptionPane.showConfirmDialog(
    this, "¿Seguro que deseas eliminar este usuario?", "Confirmar",
    javax.swing.JOptionPane.YES_NO_OPTION);
if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
    usuarioDAO.eliminar(u.getId());
    llenarTabla();
    limpiarCampos();
}
    }//GEN-LAST:event_btEliminarActionPerformed

    private void btEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEditarActionPerformed
        if (idEditando == -1) {
    // Primer clic: cargar los datos del usuario seleccionado
    int fila = Tbusuarios.getSelectedRow();
    if (fila < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un usuario de la tabla");
        return;
    }
    modelo.Usuario u = listaUsuarios.get(fila);
    txUsuario.setText(u.getUsuario());
    pwContra.setText(u.getClave());
    cbRol.setSelectedItem(u.getRol());
    idEditando = u.getId();
    btEditar.setText("Actualizar");
} else {
    // Segundo clic: guardar los cambios en la base de datos
    String clave = new String(pwContra.getPassword());
    if (txUsuario.getText().trim().isEmpty() || clave.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "El usuario y la clave son obligatorios");
        return;
    }
    if (cbRol.getSelectedIndex() <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un rol");
        return;
    }
    modelo.Usuario u = new modelo.Usuario(
        idEditando,
        txUsuario.getText().trim(),
        clave,
        cbRol.getSelectedItem().toString()
    );
    if (usuarioDAO.actualizar(u)) {
        llenarTabla();
        limpiarCampos();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar. ¿El usuario ya existe?");
    }
}
    }//GEN-LAST:event_btEditarActionPerformed


