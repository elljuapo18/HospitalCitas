    private void btGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btGuardarActionPerformed
        String clave = new String(pwContra.getPassword());
if (txUsuario.getText().trim().isEmpty() || clave.trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "El usuario y la clave son obligatorios");
    return;
}
if (cbRol.getSelectedIndex() <= 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un rol");
    return;
}
modelo.Usuario u = new modelo.Usuario(
    txUsuario.getText().trim(),
    clave,
    cbRol.getSelectedItem().toString()
);
if (usuarioDAO.insertar(u)) {
    llenarTabla();
    limpiarCampos();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar. ¿El usuario ya existe?");
}
    }//GEN-LAST:event_btGuardarActionPerformed

