    private void btEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEliminarActionPerformed
       int fila = Tbpacientes.getSelectedRow();
if (fila < 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un paciente de la tabla");
    return;
}
int respuesta = javax.swing.JOptionPane.showConfirmDialog(
    this, "¿Seguro que deseas eliminar este paciente?", "Confirmar",
    javax.swing.JOptionPane.YES_NO_OPTION);
if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
    pacienteDAO.eliminar(listaPacientes.get(fila).getCedula());
    llenarTabla();
    limpiarCampos();
}
    }//GEN-LAST:event_btEliminarActionPerformed

    private void btEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEditarActionPerformed
      if (indiceEditando == -1) {
    // Primer clic: cargar los datos del paciente seleccionado
    int fila = Tbpacientes.getSelectedRow();
    if (fila < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un paciente de la tabla");
        return;
    }
    modelo.Paciente p = listaPacientes.get(fila);
    txCedula.setText(p.getCedula());
    txNombre.setText(p.getNombre());
    txTelefono.setText(p.getTelefono());
    txDireccion.setText(p.getDireccion());
    indiceEditando = fila;
    btEditar.setText("Actualizar");
} else {
    // Segundo clic: guardar los cambios
    if (txCedula.getText().trim().isEmpty() || txNombre.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "La cédula y el nombre son obligatorios");
        return;
    }
  String cedulaAnterior = listaPacientes.get(indiceEditando).getCedula();
modelo.Paciente p = new modelo.Paciente(
    txCedula.getText().trim(),
    txNombre.getText().trim(),
    txTelefono.getText().trim(),
    txDireccion.getText().trim()
);
if (pacienteDAO.actualizar(p, cedulaAnterior)) {
    llenarTabla();
    limpiarCampos();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar. ¿La cédula ya existe?");
}
}
    }//GEN-LAST:event_btEditarActionPerformed


