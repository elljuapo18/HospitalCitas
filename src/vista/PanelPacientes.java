    private void btGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btGuardarActionPerformed
        if (txCedula.getText().trim().isEmpty() || txNombre.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "La cédula y el nombre son obligatorios");
    return;
}
modelo.Paciente p = new modelo.Paciente(
    txCedula.getText().trim(),
    txNombre.getText().trim(),
    txTelefono.getText().trim(),
    txDireccion.getText().trim()
);
if (pacienteDAO.insertar(p)) {
    llenarTabla();
    limpiarCampos();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar. ¿La cédula ya existe?");
}
    }//GEN-LAST:event_btGuardarActionPerformed

